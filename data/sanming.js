// SanMingDB Query & Search Engine
class SanMingDB {
  /**
   * Get specific Day-Hour evaluation for given Day Pillar and Hour Pillar
   * @param {string} dayPillar e.g. "甲子"
   * @param {string} hourPillar e.g. "甲子"
   */
  static getReading(dayPillar, hourPillar) {
    if (!dayPillar || !hourPillar) return null;
    const dayStem = dayPillar[0];
    const hourBranch = hourPillar[1];

    const stemHours = DAY_STEM_HOUR_EVAL[dayStem];
    if (!stemHours) return null;
    const entry = stemHours[hourBranch];
    if (!entry) return null;

    const defaultMeaning = `日干【${dayStem}】遇时支【${hourBranch}】，其气象取格为【${entry.pattern}】。${entry.summary} 此格揭示了日主元神与时宿归宿的五行生克与十神照应，反映命主晚运归宿、才干发挥及名利际遇。`;
    const defaultSource = `《三命通会》卷八/卷九·六十甲子日时断法（${dayStem}日${hourBranch}时）；互参《子平真诠·用神成败论》与《渊海子平·十神法》。`;
    const defaultConditions = `① 日元${dayStem}木火土金水需得月令提纲或地支通根生旺；② 时支${hourBranch}不可见日支或岁运重大刑冲破害（如子午相冲、丑未相刑）；③ 喜用神透干有力，忌神受制或有通关转化。`;
    const defaultUsage = `① 喜忌趋向：依日主身旺身弱调配印比或财官食伤，身旺喜克泄耗，身弱喜生扶印星；② 事业建议：依【${entry.pattern}】之特性，文贵从文职教育传媒，武贵从政法军旅经管，财官双美利于商道创业；③ 行运指导：行运逢合吉神则显达，逢破局煞曜宜低调修持。`;

    return {
      title: `${dayPillar}日 ${hourPillar}时 断法`,
      dayPillar,
      hourPillar,
      pattern: entry.pattern,
      meaning: entry.meaning || defaultMeaning,
      source: entry.source || defaultSource,
      conditions: entry.conditions || defaultConditions,
      usage: entry.usage || defaultUsage,
      summary: entry.summary,
      verse: entry.verse,
      fullClassicalText: `万民英《三命通会》卷八：${dayPillar}日生于${hourPillar}时，其象为【${entry.pattern}】。${entry.summary} 古诗云：${entry.verse}`
    };
  }

  static getPatterns() {
    return SAN_MING_PATTERNS;
  }

  static search(keyword) {
    if (!keyword) return [];
    keyword = keyword.trim().toLowerCase();
    const results = [];

    // Search across all Day-Hour entries
    for (const [stem, branches] of Object.entries(DAY_STEM_HOUR_EVAL)) {
      for (const [branch, data] of Object.entries(branches)) {
        if (
          stem.includes(keyword) ||
          branch.includes(keyword) ||
          data.pattern.includes(keyword) ||
          data.summary.includes(keyword) ||
          data.verse.includes(keyword)
        ) {
          results.push({
            source: '《三命通会》· 日时断',
            title: `${stem}日 · ${branch}时（${data.pattern}）`,
            content: data.verse,
            detail: data.summary
          });
        }
      }
    }

    // Search Patterns
    for (const p of SAN_MING_PATTERNS) {
      if (p.name.includes(keyword) || p.quote.includes(keyword) || p.essence.includes(keyword)) {
        results.push({
          source: '《三命通会》· 格局论',
          title: p.name,
          content: p.quote,
          detail: p.evaluation
        });
      }
    }

    return results;
  }
}

