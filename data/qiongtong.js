  /**
   * Search passages
   * @param {string} query 
   */
  static search(query) {
    if (!query) return [];
    const results = [];
    for (const [stem, months] of Object.entries(QIONG_TONG_DATA)) {
      for (const [branch, data] of Object.entries(months)) {
        const fullText = `${stem}生${branch}月 ${data.title} ${data.climate} ${data.classic_text} ${data.vernacular}`;
        if (fullText.includes(query)) {
          results.push({
            canon: '穷通宝鉴',
            chapter: `${stem}日主 · ${MONTH_BRANCH_NAMES[branch] || branch + '月'}`,
            passage: data.classic_text,
            commentary: `${data.climate} 调候用神：${data.primary}、${data.secondary}。${data.vernacular}`,
            matchType: fullText.includes(query) ? 'text' : 'fuzzy'
          });
        }
      }
    }
    return results;
  }
