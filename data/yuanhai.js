class YuanHaiDB {
  static getAllChapters() {
    return YUAN_HAI_DATA.chapters;
  }

  static getTenGodTreatise(godName) {
    const data = YUAN_HAI_DATA.ten_gods_treatise[godName];
    if (!data) return null;
    return data;
  }

  static search(keyword) {
    if (!keyword) return [];
    keyword = keyword.trim().toLowerCase();
    const results = [];

    // Search chapters and verses
    for (const chap of YUAN_HAI_DATA.chapters) {
      if (chap.title.includes(keyword) || chap.quote.includes(keyword) || chap.meaning.includes(keyword)) {
        results.push({
          source: '《渊海子平》· 经典篇章',
          title: chap.title,
          content: chap.quote,
          detail: chap.meaning
        });
      }
      for (const v of chap.verses) {
        if (
          v.line.includes(keyword) ||
          (v.note && v.note.includes(keyword)) ||
          (v.vernacular && v.vernacular.includes(keyword)) ||
          (v.application && v.application.includes(keyword))
        ) {
          results.push({
            source: `《渊海子平》· ${chap.title}`,
            title: v.line,
            content: v.line,
            detail: `${v.vernacular || v.note} | ${v.application || ''}`
          });
        }
      }
    }

    // Search Ten Gods
    for (const [god, info] of Object.entries(YUAN_HAI_DATA.ten_gods_treatise)) {
      const searchStr = `${god} ${info.ancient} ${info.plain_text} ${info.careers} ${info.relationships}`;
      if (searchStr.includes(keyword)) {
        results.push({
          source: '《渊海子平》· 十神实战真谛',
          title: `论【${god}】实战与职业人际`,
          content: info.plain_text,
          detail: `【适合职业】${info.careers} | 【人际】${info.relationships}`
        });
      }
    }

    return results;
  }
}

