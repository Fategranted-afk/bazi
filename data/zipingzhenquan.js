class ZiPingZhenQuanDB {
  static getPattern(patternName) {
    if (!patternName) return ZI_PING_ZHEN_QUAN_PATTERNS['正官格'];
    for (const [key, val] of Object.entries(ZI_PING_ZHEN_QUAN_PATTERNS)) {
      if (patternName.includes(key) || key.includes(patternName)) {
        return val;
      }
    }
    return ZI_PING_ZHEN_QUAN_PATTERNS['正官格'];
  }

  static getAllPatterns() {
    return ZI_PING_ZHEN_QUAN_PATTERNS;
  }

  static search(keyword) {
    if (!keyword) return [];
    keyword = keyword.trim().toLowerCase();
    const results = [];

    for (const [key, p] of Object.entries(ZI_PING_ZHEN_QUAN_PATTERNS)) {
      const vernStr = (p.vernacular && typeof p.vernacular === 'object')
        ? (p.vernacular.text || '') + (p.vernacular.translation || '') + (p.vernacular.translationEn || '') + (p.vernacular.paradigm || '') + (p.vernacular.defectWarning || '')
        : (p.vernacular || '');
      if (
        key.includes(keyword) ||
        p.meaning.includes(keyword) ||
        p.conditions.includes(keyword) ||
        p.defects.includes(keyword) ||
        p.remedies.includes(keyword) ||
        p.usage.includes(keyword) ||
        vernStr.includes(keyword)
      ) {
        results.push({
          source: '《子平真诠》· 格局论',
          title: `${p.name}（成败与救应）`,
          content: p.quote,
          detail: `【成格】${p.conditions} 【救应】${p.remedies} | ${vernStr.substring(0, 80)}...`
        });
      }
    }
    return results;
  }
}

